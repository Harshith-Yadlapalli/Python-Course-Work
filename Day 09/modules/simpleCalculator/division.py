def div(x,y):
    if y==0:
        return "Zero Division Error"
    return x/y
def floor_div(x,y):
    if y==0:
        return "ZeroDivisionError: integer division or modulo by zero"
    return x//y

def modulo(x,y):
    if y==0:
        return "ZeroDivisionError: integer division or modulo by zero"
    return x%y